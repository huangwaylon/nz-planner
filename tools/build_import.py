# -*- coding: utf-8 -*-
"""Builds import.js (the planner's import parsers) from the two tested sources, and copies the
region table next to the book's data. Authoring-time only; nothing runs at page load.

    tools/gmlist.js   -> plimport.gm   (Google Maps list / Takeout parsers, offline region lookup)
    tools/igsaved.js  -> plimport.ig   (Instagram "Export your information" parsers, matching, unzip)
    research/gm-regions.json -> data/nz/gm-regions.json

import.js exposes exactly one global, `plimport`, so it is FOLD-compliant: the tools keep their
own globals for node tests and Apps Script, the app sees neither. Edit the tools, never
import.js, then:

    node tools/gmlist.test.js && node tools/igsaved.test.js && python3 tools/build_import.py
"""
import os, re, shutil

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
rd = lambda p: open(os.path.join(ROOT, p), encoding='utf-8').read()

gm = rd('tools/gmlist.js')
ig = rd('tools/igsaved.js')
IG_API = ['parseSavedPosts', 'parseSavedCollections', 'mergeSaved', 'parseReelUrl', 'parseOgMeta',
          'matchToPlaces', 'igHandle', 'inFrame', 'fixText', 'unzipSaved']
for name in IG_API:
    assert re.search(r'\bfunction %s\b' % name, ig), name
assert 'var gmlist=(function(){' in gm

out = '''/* GENERATED by tools/build_import.py from tools/gmlist.js and tools/igsaved.js. Do not edit.
   One global, plimport = {gm, ig}. Loaded on demand when the planner's import sheet opens. */
var plimport=(function(){
'use strict';
''' + gm.replace('var gmlist=(function(){', 'const gm=(function(){', 1) + '''
const ig=(function(){
''' + ig + '''
return {''' + ', '.join(IG_API) + '''};
})();
return {gm:gm, ig:ig};
})();
'''
open(os.path.join(ROOT, 'import.js'), 'w', encoding='utf-8').write(out)
shutil.copyfile(os.path.join(ROOT, 'research', 'gm-regions.json'), os.path.join(ROOT, 'data', 'nz', 'gm-regions.json'))
print('wrote import.js (%d bytes) and data/nz/gm-regions.json' % len(out))
